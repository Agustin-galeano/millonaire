import asyncio,sys
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        pg=await b.new_page(viewport={'width':390,'height':844},device_scale_factor=2,has_touch=True)
        errs=[]
        pg.on('pageerror',lambda e:errs.append(str(e)))
        pg.on('console',lambda m:errs.append(m.text) if m.type=='error' else None)
        await pg.goto('file:///home/claude/millonaire/index.html')
        await pg.wait_for_timeout(600)
        await pg.fill('#nameIn','Agus')
        await pg.screenshot(path='v1.png')
        await pg.click('#wGo'); await pg.wait_for_timeout(300)
        await pg.click('#bShop'); await pg.wait_for_timeout(300)
        for cat in ['metal','gema','cristal','mueble','arte']:
            await pg.click(f'#catTabs .tab[data-cat={cat}]')
            n=await pg.locator('.card').count()
            for k in range(n):
                await pg.locator('.card').nth(k).click()
                if await pg.locator('#buyBtn').is_enabled(): await pg.click('#buyBtn')
                await pg.wait_for_timeout(80)
        await pg.screenshot(path='v2.png')
        await pg.click('#sheet .x'); await pg.wait_for_timeout(3500)
        await pg.screenshot(path='v3.png')
        await pg.click('#bMarket'); await pg.wait_for_timeout(300); await pg.screenshot(path='v4.png')
        await pg.locator('[data-buyl]').first.click(); await pg.wait_for_timeout(500)
        await pg.click('#bVault'); await pg.wait_for_timeout(300)
        await pg.locator('details summary').nth(2).click(); await pg.wait_for_timeout(200)
        await pg.screenshot(path='v5.png')
        await pg.locator('details[open] [data-sell]').first.click(); await pg.wait_for_timeout(300); await pg.screenshot(path='v6.png')
        await pg.click('#sellGo'); await pg.wait_for_timeout(300); await pg.screenshot(path='v7.png')
        await pg.click('#dlg .x')
        await pg.click('#bVip'); await pg.wait_for_timeout(200); await pg.screenshot(path='v8.png')
        await pg.click('#vipGo'); await pg.wait_for_timeout(300); await pg.click('#vipIn'); await pg.wait_for_timeout(1200); await pg.screenshot(path='v9.png')
        await pg.click('#backBtn'); await pg.click('#bRank'); await pg.wait_for_timeout(300); await pg.screenshot(path='v10.png')
